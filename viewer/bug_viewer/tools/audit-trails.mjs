// Usage: node tools/audit-trails.mjs. Reads actual final road geometry and height.
// Writes a per-trail report and render data; does not mutate the baked routes.
import { writeFile, mkdir } from 'node:fs/promises';
import { loadReviewWorld } from './load-review-world.mjs';

const world = await loadReviewWorld(), hw = world.highways(), routes = world.trailRoutes();
const rows = [], views = [];
for (let index = 0; index < routes.length; index++) {
  const road = routes[index], pts = road.pts;
  let maxGrade = 0, maxStep = 0, wet = 0, maxMeshError = 0, worst;
  const line = [];
  for (let i = 0; i < pts.length; i++) {
    const p = pts[i], y = world.height(p.x,p.z); line.push([p.x,y,p.z]);
    if (world.waterDepthAt(p.x,p.z)>0.1 || world.surface(p.x,p.z).key === 'water') wet++;
    if (i) {
      const a = pts[i-1], n = Math.max(1,Math.ceil(Math.hypot(p.x-a.x,p.z-a.z)/.5));
      let previous = world.height(a.x,a.z);
      for (let j=1;j<=n;j++) {
        const t=j/n, x=a.x+(p.x-a.x)*t,z=a.z+(p.z-a.z)*t,h=world.height(x,z);
        const ds=Math.hypot(p.x-a.x,p.z-a.z)/n;
        if (Math.abs(h-previous)/ds>maxGrade) { maxGrade=Math.abs(h-previous)/ds; worst={x:+x.toFixed(2),z:+z.toFixed(2),height:+h.toFixed(3),roadGrade:+hw.near(x,z).h.toFixed(3),featureDepth:+world.waterDepthAt(x,z).toFixed(3)}; }
        maxStep=Math.max(maxStep,Math.abs(h-previous)); previous=h;
        // Same 2.5 m aligned grid as the near terrain mesh, with its diagonal.
        const gx=Math.floor(x/2.5)*2.5,gz=Math.floor(z/2.5)*2.5,fx=(x-gx)/2.5,fz=(z-gz)/2.5;
        const h00=world.height(gx,gz),h10=world.height(gx+2.5,gz),h01=world.height(gx,gz+2.5),h11=world.height(gx+2.5,gz+2.5);
        const mesh=fx+fz<=1?h00+(h10-h00)*fx+(h01-h00)*fz:h11+(h01-h11)*(1-fx)+(h10-h11)*(1-fz);
        maxMeshError=Math.max(maxMeshError,Math.abs(h-mesh));
      }
    }
  }
  const ends=[pts[0],pts.at(-1)].map(p=>({ x:+p.x.toFixed(1),z:+p.z.toFixed(1),gap:+hw.crossingDistance(p.x,p.z,road).toFixed(2),surface:hw.surfaceKey(p.x,p.z) }));
  const row={trail:index+1,km:+(road.total/1000).toFixed(2),maxGradePct:+(maxGrade*100).toFixed(1),maxHalfMetreRise:+maxStep.toFixed(3),wetSamples:wet,maxMeshError:+maxMeshError.toFixed(3),worst,ends};
  rows.push(row); console.log(JSON.stringify(row));
  // Full route overview with the real ground at 10 m resolution.
  const xs=pts.map(p=>p.x),zs=pts.map(p=>p.z),x0=Math.min(...xs)-50,z0=Math.min(...zs)-50;
  const x1=Math.max(...xs)+50,z1=Math.max(...zs)+50,step=Math.max(10,(x1-x0)/130,(z1-z0)/130);
  const nx=Math.ceil((x1-x0)/step),nz=Math.ceil((z1-z0)/step),terrain=[];
  for(let z=0;z<=nz;z++)for(let x=0;x<=nx;x++)terrain.push(world.height(x0+x*step,z0+z*step));
  views.push({id:index+1,line,x0,z0,step,nx,nz,terrain});
}
await mkdir(new URL('../dist/review/',import.meta.url),{recursive:true});
await writeFile(new URL('../dist/review/trail-audit.json',import.meta.url),JSON.stringify({rows,views}));
const header='| Trail | km | Peak grade % | Largest rise / 0.5 m | Near-mesh error m | Wet samples | Start/end paved gap m |\n|---|---:|---:|---:|---:|---:|---|\n';
await writeFile(new URL('../../../docs/TRAIL_AUDIT.md',import.meta.url),`# Baked trail geometry audit\n\nGenerated by tools/audit-trails.mjs using the final real-map highway geometry and county.height. Every route is sampled at intervals no larger than 0.5 m. These are measured geometry checks; they do not certify driving feel or full gameplay. Peak grade includes authored features. Near-mesh error compares the analytic height to the 2.5 m grid used by near terrain tiles.\n\n${header}${rows.map(r=>`| ${r.trail} | ${r.km} | ${r.maxGradePct} | ${r.maxHalfMetreRise} | ${r.maxMeshError} | ${r.wetSamples} | ${r.ends.map(e=>e.gap).join(' / ')} |`).join('\n')}\n`);
